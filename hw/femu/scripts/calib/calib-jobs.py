"""Write the fio job files of the calibration matrix.

calib-matrix.json lists every workload condition of the calibration: its
immutable id, its family, its split (fit, held, lockbox or check) and its
fio options. This tool writes one fio file per condition and per
precondition step, named <id>.fio. Both the real drive and the FEMU guest
run these same files, so the request sizes and the order match.

The matrix also records the sha256 of each generated file in fio_sha256.
The calibration binds the fit and held-out split to these hashes, so a
changed job cannot keep an old id. A mismatch makes this tool exit 2.

Usage:
    calib-jobs.py [--matrix FILE] --out DIR     write the fio files
    calib-jobs.py [--matrix FILE] --print-hashes
    calib-jobs.py --self-test

Each file reads the target from the CALIB_DEV environment variable. Run
it as "fio --output-format=json FILE". Trace conditions have no fio file
yet; the replay path is not in this tree.

Exit status: 0 on success, 1 when the self-test fails, 2 on a bad matrix
or a hash mismatch.
"""

import argparse
import hashlib
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_MATRIX = os.path.join(HERE, "calib-matrix.json")
EXPECTED = os.path.join(HERE, "calib-jobs.expected")
SPLITS = ("fit", "held", "lockbox", "check")

# The split of the design note, section 2.4. The self-test holds the
# matrix to it, so an edit of the matrix cannot move an id silently.
DESIGN_FIT = {
    "J1-randread-4k-qd1", "J2-randread-4k-qd4", "J2-randread-4k-qd32",
    "J2-randread-4k-qd256", "J3-read-4k-qd32", "J3-read-128k-qd32",
    "J3-read-1m-qd32", "J4-randwrite-4k-qd1", "J5-write-128k-qd32",
    "J7-randwrite-4k-a100", "J8-randwrite-4k-a72",
}
DESIGN_HELD = {
    "J2-randread-4k-qd2", "J2-randread-4k-qd8", "J2-randread-4k-qd16",
    "J2-randread-4k-qd64", "J2-randread-4k-qd128", "J3-read-16k-qd32",
    "J3-read-64k-qd32", "J3-read-256k-qd32", "J8-randwrite-4k-a93",
    "J9-mix70-4k-qd32", "T1-alibaba-2020",
}
DESIGN_LOCKBOX = {"J9-mix70-4k-qd8", "T2-msr-cambridge"}


class MatrixError(Exception):
    pass


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def load_matrix(path):
    # the leading // lines (the SPDX tag) are not JSON
    with open(path, encoding="utf-8") as f:
        lines = f.read().split("\n")
    while lines and lines[0].startswith("//"):
        lines.pop(0)
    m = json.loads("\n".join(lines))
    check_matrix(m)
    return m


def check_matrix(m):
    if m.get("calib_matrix") != 1:
        raise MatrixError("calib_matrix must be 1")
    seen = set()
    for c in m.get("preconditions", []) + m.get("conditions", []):
        cid = c.get("id", "")
        if not cid or cid in seen:
            raise MatrixError(f"missing or repeated id '{cid}'")
        seen.add(cid)
    for c in m.get("conditions", []):
        if c.get("split") not in SPLITS:
            raise MatrixError(f"{c['id']}: split must be one of {SPLITS}")
        if c.get("family") not in m.get("families", {}):
            raise MatrixError(f"{c['id']}: unknown family")
        if ("fio" in c) == ("trace" in c):
            raise MatrixError(f"{c['id']}: needs exactly one of fio, trace")


def job_text(m, item, split):
    """The fio file of one condition or precondition step."""
    out = [
        "; generated by calib-jobs.py from calib-matrix.json; do not edit",
        f"; id={item['id']} split={split}"
        + (f" pre={item['pre']}" if "pre" in item else ""),
        "[global]",
    ]
    for k in sorted(m["fio_common"]):
        out.append(f"{k}={m['fio_common'][k]}")
    out.append(f"write_hist_log={item['id']}")
    out.append("")
    out.append(f"[{item['id']}]")
    for k in sorted(item["fio"]):
        out.append(f"{k}={item['fio'][k]}")
    return "\n".join(out) + "\n"


def jobs(m):
    """(id, text) of every fio file, in matrix order."""
    for p in m.get("preconditions", []):
        yield p["id"], job_text(m, p, "precondition")
    for c in m["conditions"]:
        if "fio" in c:
            yield c["id"], job_text(m, c, c["split"])


def hashes(m):
    return {cid: sha256_bytes(t.encode()) for cid, t in jobs(m)}


def hash_problems(m):
    """Ids whose recorded hash differs from the generated file."""
    want = hashes(m)
    have = m.get("fio_sha256", {})
    bad = [cid for cid in want if have.get(cid) != want[cid]]
    bad += [cid for cid in have if cid not in want]
    return sorted(bad)


def concat(m):
    return "".join(f"### {cid}.fio\n{t}" for cid, t in jobs(m))


def write_jobs(m, out):
    os.makedirs(out, exist_ok=True)
    for cid, t in jobs(m):
        with open(os.path.join(out, cid + ".fio"), "w", encoding="utf-8") as f:
            f.write(t)


def self_test():
    fails = []

    def check(ok, what):
        print(("ok    " if ok else "FAIL  ") + what)
        if not ok:
            fails.append(what)

    m = load_matrix(DEFAULT_MATRIX)
    with open(EXPECTED, encoding="utf-8") as f:
        expected = f.read()
    check(concat(m) == expected, "generated files equal calib-jobs.expected")
    check(not hash_problems(m), "fio_sha256 in the matrix matches each file")

    with tempfile.TemporaryDirectory() as d:
        write_jobs(m, d)
        names = sorted(os.listdir(d))
        check(len(names) == len(hashes(m)), f"wrote {len(names)} fio files")
        one = os.path.join(d, "J1-randread-4k-qd1.fio")
        with open(one, "rb") as f:
            check(sha256_bytes(f.read()) == m["fio_sha256"].get(
                "J1-randread-4k-qd1"), "file on disk has the recorded hash")

    split = {c["id"]: c["split"] for c in m["conditions"]}
    check({k for k, v in split.items() if v == "fit"} == DESIGN_FIT,
          "fit ids equal the design split")
    check({k for k, v in split.items() if v == "held"} == DESIGN_HELD,
          "held ids equal the design split")
    check({k for k, v in split.items() if v == "lockbox"} == DESIGN_LOCKBOX,
          "lockbox ids equal the design split")
    qd1 = [c["id"] for c in m["conditions"]
           if c["family"] in ("J1", "J2") and c["fio"]["iodepth"] == "1"]
    check(qd1 == ["J1-randread-4k-qd1"], "the QD1 read is counted once")

    for cid, t in jobs(m):
        bad = [w for w in ("direct=1", "ioengine=io_uring", "norandommap=1",
                           "percentile_list=50:90:99:99.9:99.99",
                           "log_hist_msec=1000",
                           "random_generator=tausworthe64",
                           "thread=1", f"write_hist_log={cid}", f"[{cid}]")
               if w + "\n" not in t]
        if bad:
            check(False, f"{cid} lacks {bad}")
    check(True, "every file carries the common options and its own name")

    # J8 writes only below the excluded range, and its trim covers the rest
    for c in m["conditions"]:
        if c["family"] == "J8":
            a = c["active_pcent"]
            trim = [p for p in m["preconditions"]
                    if p["id"] == f"X-trim-a{a}"][0]["fio"]
            ok = (c["fio"]["size"] == f"{a}%" and "offset" not in c["fio"]
                  and trim["offset"] == f"{a}%"
                  and trim["size"] == f"{100 - a}%")
            check(ok, f"{c['id']}: active {a}% and trim of the rest")

    # controls: a changed option or a moved id must break the hash check
    m2 = json.loads(json.dumps(m))
    m2["conditions"][2]["fio"]["iodepth"] = "2"
    check(hash_problems(m2) == [m2["conditions"][2]["id"]],
          "control: a changed iodepth fails the hash check")
    m3 = json.loads(json.dumps(m))
    m3["conditions"][3]["split"] = "fit"
    check(hash_problems(m3) == [m3["conditions"][3]["id"]],
          "control: a moved split fails the hash check")
    check(concat(m2) != expected, "control: a changed option differs "
          "from the expected file")

    print("calib-jobs self-test: " + ("FAIL" if fails else "PASS"))
    return 1 if fails else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--matrix", default=DEFAULT_MATRIX)
    ap.add_argument("--out", help="folder for the fio files")
    ap.add_argument("--print-hashes", action="store_true",
                    help="print the fio_sha256 map of the matrix")
    ap.add_argument("--write-expected", action="store_true",
                    help=argparse.SUPPRESS)
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    try:
        m = load_matrix(a.matrix)
    except (OSError, ValueError, MatrixError) as e:
        print(f"calib-jobs: {e}", file=sys.stderr)
        return 2
    if a.print_hashes:
        print(json.dumps(hashes(m), indent=2, sort_keys=False))
        return 0
    if a.write_expected:
        with open(EXPECTED, "w", encoding="utf-8") as f:
            f.write(concat(m))
        return 0
    bad = hash_problems(m)
    if bad:
        print("calib-jobs: fio_sha256 does not match: " + ", ".join(bad),
              file=sys.stderr)
        return 2
    if not a.out:
        ap.error("--out is required")
    write_jobs(m, a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
