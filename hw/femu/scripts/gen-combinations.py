"""Generate the supported-combination reference from the refusal code.

Every error_setg(errp, "...") in hw/femu is a combination that realize or a
runtime setter refuses. This script reads them, finds the device
properties each message names, and writes
hw/femu/docs/reference/combinations.md: one section per property, listing
the messages that name it. With --check it compares instead of writing and
fails on a difference, so the page follows the code.

Usage:
    gen-combinations.py [--check]
    gen-combinations.py --self-test
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
FEMU = ROOT / "hw" / "femu"
OUT = FEMU / "docs" / "reference" / "combinations.md"

CALL = re.compile(r'error_setg\(\s*errp\s*,((?:\s*"(?:[^"\\]|\\.)*")+)')
LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')
PROP = re.compile(r'^\s*\{\s*"([a-z][a-z0-9_.-]*)",', re.M)

HEADER = """<!--
Generated by hw/femu/scripts/gen-combinations.py from the refusal messages
in hw/femu. Do not edit by hand: change the message in the code, then run
  python3 hw/femu/scripts/gen-combinations.py
-->

# Supported combinations

Each section is a device property and the refusals that name it: the
messages realize, or a runtime setter, gives for a combination FEMU does
not support. A property with no section combines with everything that its
own description allows. A message keeps its format directives (`%s`,
`%d`), which the running device fills in.
"""


def messages(root):
    """(file, message) for every error_setg in the C sources under @root."""
    out = []
    for path in sorted(root.rglob("*.c")):
        if "tests" in path.parts:
            continue
        text = path.read_text(errors="replace")
        for m in CALL.finditer(text):
            msg = "".join(LITERAL.findall(m.group(1)))
            msg = msg.replace('\\"', '"').strip()
            if msg:
                out.append((path.relative_to(ROOT).as_posix(), msg))
    return out


def properties(root):
    """The device property names that femu-props.c describes."""
    text = (root / "femu-props.c").read_text()
    return sorted(set(PROP.findall(text)))


def render(msgs, props):
    by_prop = {}
    for _, msg in msgs:
        words = set(re.findall(r"[a-z][a-z0-9_]*", msg))
        for p in props:
            if p in words:
                by_prop.setdefault(p, set()).add(msg)
    lines = [HEADER]
    for p in sorted(by_prop):
        lines.append("## `%s`\n" % p)
        for msg in sorted(by_prop[p]):
            lines.append("- %s" % msg.replace("|", "\\|"))
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def self_test():
    src = ('error_setg(errp, "lockdown does not work with a femu-subsys '
           '"\n "yet");\nerror_setg(errp, "x needs %s", a);')
    found = ["".join(LITERAL.findall(m.group(1)))
             for m in CALL.finditer(src)]
    assert found == ["lockdown does not work with a femu-subsys yet",
                     "x needs %s"], found
    page = render([("f.c", found[0])], ["lockdown", "ocp"])
    assert "## `lockdown`" in page and "## `ocp`" not in page, page
    print("gen-combinations: self-test passed")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()
    if args.self_test:
        self_test()
        return 0
    page = render(messages(FEMU), properties(FEMU))
    if args.check:
        if not OUT.exists() or OUT.read_text() != page:
            print("gen-combinations: %s is out of date; run "
                  "hw/femu/scripts/gen-combinations.py" % OUT.relative_to(ROOT))
            return 1
        print("gen-combinations: %s is current" % OUT.relative_to(ROOT))
        return 0
    OUT.write_text(page)
    print("gen-combinations: wrote %s" % OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
